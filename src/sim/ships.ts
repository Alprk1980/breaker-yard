import { CELL_COUNT, HEIGHT, WIDTH } from './constants';
import { BIN_NAMES, MATERIAL_BIN, MATERIAL_COUNT, MATERIAL_VALUE, Material } from './materials';
import { DEMO } from './scenes';
import type { Simulation } from './Simulation';
import { TileFlags } from './TileFlags';
import { World } from './World';

/**
 * Ship blueprints: compact, parametric descriptions of a derelict that `buildShip` turns
 * into tiles at the dock. Coordinates are local to the hull: (0, 0) is the top-left tile of
 * the outer frame, which is a ring of load-bearing girders around the deck. Lines are
 * `[x1, y1, x2, y2]`, inclusive and axis-aligned; rects are `[x, y, w, h]`.
 *
 * Blueprints are content, generated by the local model (`tools/qwen-gen.mjs ships`) and
 * held to `shipErrors`, which builds each ship in a real world and checks it stands up,
 * holds air, can be worked by its crew and pays a fair contract.
 */
export interface ShipContract {
  client: string;
  brief: string;
  /** Credits the crew must deliver to pass. */
  quota: number;
  /** Seconds on the clock. */
  timeLimit: number;
}

export interface ShipBlueprint {
  id: string;
  name: string;
  description: string;
  width: number;
  height: number;
  /** Local rows on the left frame where the two gantry arms attach. */
  arms: number[];
  /** Interior walls. */
  bulkheads: number[][];
  /** Interior load-bearing girders: walls that also carry load. */
  girders: number[][];
  /** Openings cut through bulkheads, `[x, y]`. */
  doors: number[][];
  /** Engine block: a line on the frame (not the docked left side). Heavy and valuable. */
  engine: number[];
  /** Solid electronics rects. */
  consoles: number[][];
  /** Compartment pressures, `[x, y, bar]` on any deck tile of the compartment. Others hold 1 bar. */
  atmosphere: number[][];
  /** Toxic leak deck tiles, `[x, y]`. */
  leaks: number[][];
  /** Crew start tiles, `[x, y]`. */
  crew: number[][];
  contract: ShipContract;
}

/** Where every ship docks: hull's left frame column, and the gantry it hangs from. */
export const SHIP_X0 = 48;
export const GANTRY_X = 38;
/** Gantry overhang above and below the hull. */
const GANTRY_OVERHANG = 8;
export const ENGINE_MASS = 6;

export const SHIP_LIMITS = {
  minWidth: 16,
  maxWidth: 38,
  minHeight: 12,
  maxHeight: 40,
  minValue: 2500,
  maxValue: 15000,
  maxBinShare: 0.75,
  minQuotaShare: 0.25,
  maxQuotaShare: 0.6,
  minTime: 240,
  maxTime: 900,
  /**
   * The clock must suit the job: about `timeBase` seconds plus `timePerDeck` per deck tile,
   * give or take `timeSlack`, inside minTime-maxTime.
   */
  timeBase: 200,
  timePerDeck: 0.5,
  timeSlack: 0.3,
  /** Peak member utilisation an intact ship may sit at. */
  maxStress: 0.85,
} as const;

const { FLOOR, BULKHEAD, GIRDER, HAZARD_LEAK } = TileFlags;
const FRAME = GIRDER | BULKHEAD;

/** Top-left tile of the hull in the world. Ships are centred on the yard's middle row. */
export function shipOrigin(bp: ShipBlueprint): { x0: number; y0: number } {
  return { x0: SHIP_X0, y0: 64 - (bp.height >> 1) };
}

function eachOnLine(line: number[], visit: (x: number, y: number) => void): void {
  const [x1, y1, x2, y2] = line;
  const dx = Math.sign(x2 - x1);
  const dy = Math.sign(y2 - y1);
  const n = Math.max(Math.abs(x2 - x1), Math.abs(y2 - y1));
  for (let k = 0; k <= n; k++) visit(x1 + dx * k, y1 + dy * k);
}

/**
 * Flood-fills deck tiles (4-connected) from `start`, writing their indices to `out`.
 * Returns how many it found; `mark` gets `stamp` on each, and tiles marked negative are
 * treated as walls.
 */
function deckRegion(world: World, start: number, out: Int32Array, mark: Int32Array, stamp: number): number {
  if ((world.tiles[start] & FLOOR) === 0) return 0;
  let head = 0;
  let tail = 0;
  out[tail++] = start;
  mark[start] = stamp;
  while (head < tail) {
    const i = out[head++];
    const x = i % WIDTH;
    const y = (i / WIDTH) | 0;
    for (let d = 0; d < 4; d++) {
      const nx = d === 0 ? x - 1 : d === 1 ? x + 1 : x;
      const ny = d === 2 ? y - 1 : d === 3 ? y + 1 : y;
      if (nx < 0 || ny < 0 || nx >= WIDTH || ny >= HEIGHT) continue;
      const j = ny * WIDTH + nx;
      // A negative mark is a blocked tile (a doorway, when counting rooms).
      if (mark[j] === stamp || mark[j] < 0 || (world.tiles[j] & FLOOR) === 0) continue;
      mark[j] = stamp;
      out[tail++] = j;
    }
  }
  return tail;
}

/** Builds `bp` at the dock: hull, gantry, anchors, salvage bins, air. Clears the world first. */
export function buildShip(world: World, bp: ShipBlueprint): void {
  world.clear();
  world.lattice.breakThreshold = DEMO.breakThreshold;
  world.lattice.edgeCapacity.fill(DEMO.breakThreshold);
  const { x0, y0 } = shipOrigin(bp);
  const w = bp.width;
  const h = bp.height;
  const at = (x: number, y: number): number => world.tiles[world.index(x0 + x, y0 + y)];

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const edge = x === 0 || y === 0 || x === w - 1 || y === h - 1;
      world.setTile(x0 + x, y0 + y, edge ? FRAME : FLOOR);
    }
  }
  for (const line of bp.girders) eachOnLine(line, (x, y) => world.setTile(x0 + x, y0 + y, FRAME));
  for (const line of bp.bulkheads) {
    eachOnLine(line, (x, y) => {
      if ((at(x, y) & GIRDER) === 0) world.setTile(x0 + x, y0 + y, BULKHEAD);
    });
  }
  for (const [x, y] of bp.doors) {
    if (at(x, y) === BULKHEAD) world.setTile(x0 + x, y0 + y, FLOOR);
  }
  for (const [cx, cy, cw, ch] of bp.consoles) {
    for (let y = cy; y < cy + ch; y++) {
      for (let x = cx; x < cx + cw; x++) world.setTile(x0 + x, y0 + y, BULKHEAD, 1, Material.ELECTRONICS);
    }
  }
  eachOnLine(bp.engine, (x, y) => world.setTile(x0 + x, y0 + y, FRAME, ENGINE_MASS, Material.ENGINE_PART));
  for (const [x, y] of bp.leaks) {
    if ((at(x, y) & FLOOR) !== 0) world.setTile(x0 + x, y0 + y, FLOOR | HAZARD_LEAK);
  }

  // Gantry: a column docked to the yard at both ends, with an arm to each attachment row.
  const gy0 = Math.max(2, y0 - GANTRY_OVERHANG);
  const gy1 = Math.min(HEIGHT - 3, y0 + h - 1 + GANTRY_OVERHANG);
  for (let y = gy0; y <= gy1; y++) world.setTile(GANTRY_X, y, GIRDER);
  for (const row of bp.arms) {
    for (let x = GANTRY_X + 1; x < x0; x++) world.setTile(x, y0 + row, GIRDER);
  }
  world.setTile(GANTRY_X - 1, gy0, GIRDER);
  world.setTile(GANTRY_X - 1, gy1, GIRDER);
  for (const [x, y] of [[GANTRY_X, gy0], [GANTRY_X - 1, gy0], [GANTRY_X, gy1], [GANTRY_X - 1, gy1]]) {
    world.lattice.setAnchor(x, y, true);
  }
  for (const z of DEMO.zones) world.salvage.addZone(z.bin, z.x0, z.y0, z.x1, z.y1);

  // Air: 1 bar throughout, then each listed compartment at its own pressure.
  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) world.gas.setPressure(x0 + x, y0 + y, 1);
  }
  const region = new Int32Array(CELL_COUNT);
  const mark = new Int32Array(CELL_COUNT);
  bp.atmosphere.forEach(([x, y, bar], k) => {
    const n = deckRegion(world, world.index(x0 + x, y0 + y), region, mark, k + 1);
    for (let r = 0; r < n; r++) world.gas.setPressure(region[r] % WIDTH, (region[r] / WIDTH) | 0, bar);
  });
  world.lattice.solve();
}

/** Spawns the blueprint's crew on their start tiles. */
export function seedShipCrew(sim: Simulation, bp: ShipBlueprint): void {
  const { x0, y0 } = shipOrigin(bp);
  for (const [x, y] of bp.crew) sim.pawns.spawn(x0 + x, y0 + y);
}

/** Credits per bin if every tile of the hull were delivered to the right bin, and the total. */
export function shipValue(world: World, bp: ShipBlueprint): { total: number; perBin: number[] } {
  const { x0, y0 } = shipOrigin(bp);
  const perBin = new Array(BIN_NAMES.length).fill(0);
  let total = 0;
  for (let y = 0; y < bp.height; y++) {
    for (let x = 0; x < bp.width; x++) {
      const m = world.material[world.index(x0 + x, y0 + y)];
      if (m === Material.NONE || m >= MATERIAL_COUNT) continue;
      total += MATERIAL_VALUE[m];
      perBin[MATERIAL_BIN[m]] += MATERIAL_VALUE[m];
    }
  }
  return { total, perBin };
}

const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const EMOJI = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/u;
const FIELDS = [
  'id', 'name', 'description', 'width', 'height', 'arms', 'bulkheads', 'girders', 'doors',
  'engine', 'consoles', 'atmosphere', 'leaks', 'crew', 'contract',
];

function isInt(v: unknown): v is number {
  return typeof v === 'number' && Number.isInteger(v);
}

function text(out: string[], label: string, v: unknown, min: number, max: number): void {
  if (typeof v !== 'string' || v.length < min || v.length > max) out.push(`${label}: ${min}-${max} characters`);
  else if (EMOJI.test(v)) out.push(`${label}: no emoji`);
}

/** Checks a list of integer tuples of one length; returns false (with errors) when malformed. */
function tuples(out: string[], label: string, v: unknown, len: number, maxCount: number): v is number[][] {
  if (!Array.isArray(v) || v.length > maxCount) {
    out.push(`${label}: a list of at most ${maxCount} [${len} whole numbers] entries`);
    return false;
  }
  for (const t of v) {
    if (!Array.isArray(t) || t.length !== len || !t.every(isInt)) {
      out.push(`${label}: every entry must be ${len} whole numbers, got ${JSON.stringify(t)}`);
      return false;
    }
  }
  return true;
}

/**
 * Problems with one blueprint; empty when the ship is usable. Shape first; if the shape is
 * sound the ship is built in a scratch world and checked for structure, air, layout,
 * reachability, hazards, value and contract terms. Every message names the local tile or
 * the number that failed, so it can be fixed from the message alone.
 */
export function shipErrors(entry: unknown): string[] {
  if (typeof entry !== 'object' || entry === null) return ['ship: must be an object'];
  const s = entry as Record<string, unknown>;
  const id = typeof s.id === 'string' ? s.id : '?';
  const out: string[] = [];
  const err = (msg: string): void => {
    out.push(`${id}: ${msg}`);
  };

  if (typeof s.id !== 'string' || !ID.test(s.id) || s.id.length > 32) err('id must be kebab-case, at most 32 characters');
  text(out, `${id}: name`, s.name, 3, 32);
  text(out, `${id}: description`, s.description, 20, 160);
  const extra = Object.keys(s).filter((k) => !FIELDS.includes(k));
  if (extra.length > 0) err(`unknown field(s) ${extra.join(', ')}`);
  const L = SHIP_LIMITS;
  if (!isInt(s.width) || s.width < L.minWidth || s.width > L.maxWidth) err(`width must be ${L.minWidth}-${L.maxWidth}`);
  if (!isInt(s.height) || s.height < L.minHeight || s.height > L.maxHeight) err(`height must be ${L.minHeight}-${L.maxHeight}`);
  const shapeOk =
    tuples(out, `${id}: bulkheads`, s.bulkheads, 4, 24) &&
    tuples(out, `${id}: girders`, s.girders, 4, 12) &&
    tuples(out, `${id}: doors`, s.doors, 2, 32) &&
    tuples(out, `${id}: consoles`, s.consoles, 4, 8) &&
    tuples(out, `${id}: atmosphere`, s.atmosphere, 3, 8) &&
    tuples(out, `${id}: leaks`, s.leaks, 2, 3) &&
    tuples(out, `${id}: crew`, s.crew, 2, 3);
  if (!Array.isArray(s.arms) || s.arms.length !== 2 || !s.arms.every(isInt)) err('arms must be 2 whole-number rows');
  if (!Array.isArray(s.engine) || s.engine.length !== 4 || !s.engine.every(isInt)) err('engine must be [x1, y1, x2, y2]');
  const c = s.contract as Record<string, unknown> | undefined;
  if (typeof c !== 'object' || c === null) err('contract must be an object with client, brief, quota, timeLimit');
  else {
    text(out, `${id}: contract.client`, c.client, 3, 30);
    text(out, `${id}: contract.brief`, c.brief, 20, 200);
    if (!isInt(c.quota) || c.quota < 1) err('contract.quota must be a whole number of credits');
    if (!isInt(c.timeLimit) || c.timeLimit < L.minTime || c.timeLimit > L.maxTime) {
      err(`contract.timeLimit must be ${L.minTime}-${L.maxTime} seconds`);
    }
    const ce = Object.keys(c).filter((k) => !['client', 'brief', 'quota', 'timeLimit'].includes(k));
    if (ce.length > 0) err(`contract: unknown field(s) ${ce.join(', ')}`);
  }
  if (out.length > 0 || !shapeOk) return out;

  const bp = entry as ShipBlueprint;
  const w = bp.width;
  const h = bp.height;
  const inside = (x: number, y: number): boolean => x >= 1 && y >= 1 && x <= w - 2 && y <= h - 2;
  const onFrame = (x: number, y: number): boolean =>
    x >= 0 && y >= 0 && x < w && y < h && (x === 0 || y === 0 || x === w - 1 || y === h - 1);

  // Geometry that must hold before the ship is built.
  const [a1, a2] = bp.arms;
  for (const a of bp.arms) if (a < 1 || a > h - 2) err(`arm row ${a} must be 1-${h - 2}`);
  if (Math.abs(a1 - a2) < 4) err(`arm rows ${a1} and ${a2} must be at least 4 apart`);
  const line = (label: string, l: number[], ok: (x: number, y: number) => boolean, where: string): void => {
    if (l[0] !== l[2] && l[1] !== l[3]) {
      err(`${label} ${JSON.stringify(l)} must be horizontal or vertical`);
      return;
    }
    let bad = false;
    eachOnLine(l, (x, y) => {
      if (!ok(x, y)) bad = true;
    });
    if (bad) err(`${label} ${JSON.stringify(l)} must lie ${where}`);
  };
  const interior = `inside the frame (x 1-${w - 2}, y 1-${h - 2})`;
  for (const l of bp.bulkheads) line('bulkhead', l, inside, interior);
  for (const l of bp.girders) line('girder', l, inside, interior);
  line('engine', bp.engine, (x, y) => onFrame(x, y) && x !== 0, `on the frame ring (x 0 or ${w - 1}, or y 0 or ${h - 1}), not on the docked left side x 0`);
  let engineTiles = 0;
  if (out.length === 0) eachOnLine(bp.engine, () => engineTiles++);
  if (engineTiles < 3 || engineTiles > 16) err(`engine has ${engineTiles} tiles; make it 3-16 long`);
  let consoleTiles = 0;
  for (const [x, y, cw, ch] of bp.consoles) {
    if (cw < 1 || ch < 1 || !inside(x, y) || !inside(x + cw - 1, y + ch - 1)) {
      err(`console ${JSON.stringify([x, y, cw, ch])} must be a rect ${interior}`);
    }
    consoleTiles += Math.max(0, cw) * Math.max(0, ch);
  }
  if (consoleTiles < 2 || consoleTiles > 20) err(`consoles cover ${consoleTiles} tiles; make them 2-20 in total`);
  for (const [x, y, bar] of bp.atmosphere) {
    if (!inside(x, y)) err(`atmosphere point (${x}, ${y}) must be ${interior}`);
    if (bar < 0 || bar > 6) err(`atmosphere at (${x}, ${y}) is ${bar} bar; use 0-6`);
  }
  if (bp.crew.length < 1) err('crew needs 1-3 start tiles');
  if (out.length > 0) return out;

  // Build it.
  const world = new World();
  buildShip(world, bp);
  const { x0, y0 } = shipOrigin(bp);
  const tile = (x: number, y: number): number => world.tiles[world.index(x0 + x, y0 + y)];
  const isDeck = (x: number, y: number): boolean => (tile(x, y) & FLOOR) !== 0;

  const onAny = (lines: number[][], x: number, y: number): boolean =>
    lines.some((l) => {
      let hit = false;
      eachOnLine(l, (lx, ly) => {
        if (lx === x && ly === y) hit = true;
      });
      return hit;
    });
  for (const [x, y] of bp.doors) {
    if (!onAny(bp.bulkheads, x, y) || !inside(x, y) || !isDeck(x, y)) {
      err(`door (${x}, ${y}) is not on a bulkhead tile (it must replace a bulkhead, not a girder, console or deck)`);
    }
  }
  for (const [x, y] of bp.leaks) if (!inside(x, y) || !isDeck(x, y)) err(`leak (${x}, ${y}) must be on a deck tile`);
  for (const [x, y] of bp.crew) if (!inside(x, y) || !isDeck(x, y)) err(`crew start (${x}, ${y}) must be on a deck tile`);
  for (const [x, y] of bp.atmosphere) if (inside(x, y) && !isDeck(x, y)) err(`atmosphere point (${x}, ${y}) must be on a deck tile`);
  if (out.length > 0) return out;

  // Rooms: deck areas bounded by walls, with doorways counted as walls (air flows through
  // them, but they are where one room ends and the next begins).
  const region = new Int32Array(CELL_COUNT);
  const mark = new Int32Array(CELL_COUNT);
  for (const [x, y] of bp.doors) mark[world.index(x0 + x, y0 + y)] = -1;
  let stamp = 1;
  let rooms = 0;
  let deck = bp.doors.length;
  for (let y = 1; y < h - 1; y++) {
    for (let x = 1; x < w - 1; x++) {
      const i = world.index(x0 + x, y0 + y);
      if (!isDeck(x, y) || mark[i] !== 0) continue;
      const n = deckRegion(world, i, region, mark, stamp++);
      rooms++;
      deck += n;
      if (n < 4) err(`the room at (${x}, ${y}) has only ${n} deck tiles; make every room at least 4 tiles or merge it`);
    }
  }
  if (rooms < 2 || rooms > 12) {
    err(`the hull has ${rooms} room(s) (deck areas bounded by walls, doors counted as walls); use bulkheads to make 2-12`);
  }

  // Crew reach.
  const reach = new Int32Array(CELL_COUNT);
  const [cx, cy] = bp.crew[0];
  const reached = deckRegion(world, world.index(x0 + cx, y0 + cy), region, reach, 1);
  for (const [x, y] of bp.crew) {
    if (reach[world.index(x0 + x, y0 + y)] !== 1) err(`crew start (${x}, ${y}) is not in the same compartment as (${cx}, ${cy})`);
  }
  if (reached < deck * 0.5) {
    err(`the crew can walk to only ${Math.round((100 * reached) / deck)}% of the deck from (${cx}, ${cy}); add doors so they reach at least 50%`);
  }
  const reachable = (x: number, y: number): boolean => {
    for (let d = 0; d < 4; d++) {
      const nx = d === 0 ? x - 1 : d === 1 ? x + 1 : x;
      const ny = d === 2 ? y - 1 : d === 3 ? y + 1 : y;
      if (reach[world.index(x0 + nx, y0 + ny)] === 1) return true;
    }
    return false;
  };
  for (const [x, y, cw, ch] of bp.consoles) {
    let ok = false;
    for (let yy = y; yy < y + ch; yy++) for (let xx = x; xx < x + cw; xx++) if (reachable(xx, yy)) ok = true;
    if (!ok) err(`console ${JSON.stringify([x, y, cw, ch])} has no deck tile next to it that the crew can reach`);
  }
  let engineReach = false;
  eachOnLine(bp.engine, (x, y) => {
    if (reachable(x, y)) engineReach = true;
  });
  if (!engineReach) err('the engine has no deck tile next to it that the crew can reach');

  // Hazards: what the crew does not see coming.
  let overpressure = 0;
  let vacuum = 0;
  for (const [, , bar] of bp.atmosphere) {
    if (bar > 1.5) overpressure++;
    if (bar < 0.2) vacuum++;
  }
  const hazards = overpressure + vacuum + bp.leaks.length;
  if (hazards < 1 || hazards > 4) {
    err(`${hazards} hazard(s) (compartments over 1.5 bar or under 0.2 bar, plus leaks); use 1-4`);
  }
  if (overpressure > 2) err(`${overpressure} overpressure compartments; use at most 2`);

  // Structure and air: it must hang off its arms and hold pressure untouched.
  let peak = 0;
  let px = 0;
  let py = 0;
  for (let t = 0; t < 200; t++) world.tick();
  const lattice = world.lattice;
  for (let n = 0; n < lattice.nodeCount; n++) {
    if (lattice.nodeActive[n] === 1 && lattice.nodeStress[n] > peak) {
      peak = lattice.nodeStress[n];
      px = (n % WIDTH) - x0;
      py = ((n / WIDTH) | 0) - y0;
    }
  }
  if (lattice.totalSnapped > 0 || world.debris.count > 0) {
    err('the frame snaps under its own weight before anyone touches it; move the arms toward the heavy end, add interior girders, or lighten the engine');
  } else if (peak > SHIP_LIMITS.maxStress) {
    err(
      `the frame sits at ${Math.round(peak * 100)}% of breaking load near (${px}, ${py}); keep it under ${SHIP_LIMITS.maxStress * 100}% ` +
        'by moving the arms toward the engine end, adding interior girders, or shortening the hull',
    );
  }
  if (world.gas.vacuumAbsorbed > 0.01) err('the hull leaks air to space; the frame ring must be unbroken');

  // Value and contract.
  const value = shipValue(world, bp);
  if (value.total < L.minValue || value.total > L.maxValue) {
    err(`the ship is worth ${value.total} credits sorted; make it ${L.minValue}-${L.maxValue} (size, engine length and consoles drive it)`);
  }
  for (let b = 1; b < value.perBin.length; b++) {
    if (value.perBin[b] > value.total * L.maxBinShare) {
      err(`the ${BIN_NAMES[b]} takes ${Math.round((100 * value.perBin[b]) / value.total)}% of the ship's value; keep every bin under ${L.maxBinShare * 100}%`);
    }
  }
  const est = L.timeBase + deck * L.timePerDeck;
  const tLo = Math.max(L.minTime, Math.ceil(est * (1 - L.timeSlack)));
  const tHi = Math.min(L.maxTime, Math.floor(est * (1 + L.timeSlack)));
  const time = bp.contract.timeLimit;
  if (time < tLo || time > tHi) {
    err(`contract.timeLimit ${time} s does not suit a ship with ${deck} deck tiles; set it to ${tLo}-${tHi} seconds`);
  }
  const quota = bp.contract.quota;
  const lo = Math.ceil(value.total * L.minQuotaShare);
  const hi = Math.floor(value.total * L.maxQuotaShare);
  if (quota < lo || quota > hi) {
    err(`contract.quota ${quota} is ${Math.round((100 * quota) / value.total)}% of the ship's ${value.total} credits; set it to ${lo}-${hi}`);
  }
  return out;
}
